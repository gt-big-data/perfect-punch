CREATE TABLE IF NOT EXISTS game_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    end_time TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    session_data JSONB NOT NULL
);

CREATE INDEX IF NOT EXISTS game_sessions_session_id_end_time_idx
    ON game_sessions (session_id, end_time DESC);

CREATE INDEX IF NOT EXISTS game_sessions_user_id_created_at_idx
    ON game_sessions (user_id, created_at DESC);
